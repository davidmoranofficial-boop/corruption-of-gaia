def shirt_details(fig, d, f, cv, bm):
    # torn sleeve ends and a ragged hem: a few shade pixels where the shirt stops
    for (x, y) in find(bm, 'aiA'):
        if y + 1 < FH and bm[y + 1][x] in 'cfF': cv.put(x, y, LINEN[2])
    if d == 'down':
        for (x, y) in find(bm, 'y'):
            if y == min(yy for _, yy in find(bm, 'y')): cv.put(x + 3, y, LINEN[2])   # the open collar


def jerkin_details(fig, d, f, cv, bm):
    chest = find(bm, 'ytT')
    if not chest: return
    if d == 'down':
        xs = sorted(set(x for x, _ in chest)); cx = xs[len(xs) // 2]
        for (x, y) in chest:
            if x == cx and y % 2 == 0: cv.put(x, y, '#c9a44f')    # lacing
        top = min(y for _, y in chest)
        for (x, y) in chest:
            if y == top: cv.put(x, y, LEATHER[2])                # the collar
    for (x, y) in find(bm, 'aiA'):                                # leather shoulders over a linen sleeve
        if y + 1 < FH and bm[y + 1][x] in 'aiA' and y - 1 >= 0 and bm[y - 1][x] in 'aiA': cv.put(x, y, LINEN[1] if bm[y][x] != 'A' else LINEN[2])


def trouser_details(fig, d, f, cv, bm):
    # a rope belt, knotted
    for (x, y) in find(bm, 'u'): cv.put(x, y, ROPE[0])
    # torn at the shin
    for (x, y) in find(bm, 'pgG'):
        if y + 1 < FH and bm[y + 1][x] in 'vxX' and (x + y) % 2: cv.put(x, y, SLATE[2])


def boot_details(fig, d, f, cv, bm):
    for (x, y) in find(bm, 'v'): cv.put(x, y, '#b5ab98')          # salt on the toes


def tall_boot_details(fig, d, f, cv, bm):
    tops = {}
    for (x, y) in find(bm, 'pgG'):
        tops[x] = min(tops.get(x, 99), y)
    for x, y in tops.items(): cv.put(x, y, DARKLEATHER[0])          # the turned-down top
    for (x, y) in find(bm, 'g'):
        if y == tops.get(x, 0) + 1: cv.put(x, y, '#8e6e30')        # a buckle


def glove_details(fig, d, f, cv, bm):
    for (x, y) in find(bm, 'cfF'):
        if y + 1 < FH and bm[y + 1][x] in 'jkK': cv.put(x, y, WORKGLOVE[0])   # the cuff


