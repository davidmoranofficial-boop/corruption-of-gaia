"""The walking sprites: you (and everyone else) on the world map, 16 x 24 a frame.

    python3 Tools/Art/walk.py            (also run by build.py; writes Sprites/Walk and Sprites/WalkGear)

A sheet is 3 frames across (standing, step, other step) and 4 rows down (down, up, left, right; right is left
mirrored), the same layout as before, so the game moves through it the same way.

How it's put together
- The body is drawn once per frame as a map of parts: each letter says which part a pixel belongs to (skin, chest,
  upper arm, forearm, hand, belt, thigh, shin, foot) and how lit it is (light, middle, shade). See PARTS.
- A layer colours some of those parts. The bare body colours all of them (skin, plain smallclothes); a shirt colours
  the chest and arms; trousers the belt, thighs and shins; boots the feet. Every layer is cut from the same map, so
  they always line up, in every frame, for both figures.
- Hair, beards, helmets and weapons are drawn on top, placed by the head and hands of each frame.
- The game stacks the layers (GameUI.Travel.cs PlayerLayers): whatever you wear is what you see walking about.
  Townsfolk are the same parts flattened into one sheet each (NPCS).
- The body layer carries the outline all round; anything that sticks out past the body (hair, a helmet, a bow)
  carries its own outline there.
"""
