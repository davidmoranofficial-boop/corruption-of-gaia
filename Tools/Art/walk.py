def key(s):
    return s.replace(' ', '_')


def gear_frame(gid, fig, layer, d, f):
    if layer == 'back': return item_canvas(gid, 'back', fig, d, f)
    if gid in GEAR_LOOKS:
        bm = body_map(fig, d, f)
        return outline(gear_canvas(gid, fig, d, f), keep_out=silhouette(bm))
    return item_canvas(gid, 'front', fig, d, f)


def main(out=SPR):
    walk = os.path.join(out, 'Walk')
    gear = os.path.join(out, 'WalkGear')
    os.makedirs(walk, exist_ok=True)
    os.makedirs(gear, exist_ok=True)
    made = []

    def save(img, folder, name):
        p = os.path.join(folder, name + '.png')
        img.save(p)
        made.append(p)

    for fig in ('male', 'female'):
        for skin in SKINS:
            save(make_sheet(lambda d, f: body_frame(fig, skin, d, f)), walk, 'body_%s_%s' % (fig, skin))
    for style in HAIR_STYLES:
        if style == 'bald': continue
        for hc, ramp in HAIR3.items():
            # hair doesn't depend on the figure (both share a head), so it's drawn on the masculine one's outline
            save(make_sheet(lambda d, f: hair_canvas(style, ramp, 'male', d, f)), walk, 'hair_%s_%s' % (style, key(hc)))
            save(make_sheet(lambda d, f: hair_canvas(style, ramp, 'male', d, f, capped=True)), walk, 'hair_%s_%s_cap' % (style, key(hc)))
    for style in BEARD_STYLES:
        for hc, ramp in HAIR3.items():
            save(make_sheet(lambda d, f: hair_canvas(style, ramp, 'male', d, f, beard=True)), walk, 'beard_%s_%s' % (style, key(hc)))
    ids = set(GEAR_LOOKS) | set(ITEM_ART)
    for gid in sorted(ids):
        for fig in ('male', 'female'):
            save(make_sheet(lambda d, f: gear_frame(gid, fig, 'front', d, f)), gear, '%s_%s' % (gid, fig))
            if has_layer(gid, 'back'):
                save(make_sheet(lambda d, f: gear_frame(gid, fig, 'back', d, f)), gear, '%s_%s_back' % (gid, fig))
    for name in NPCS:
        save(make_sheet(lambda d, f: npc_frame(name, d, f)), walk, name)
    return made


if __name__ == '__main__':
    print('%d walking sheets' % len(main()))
