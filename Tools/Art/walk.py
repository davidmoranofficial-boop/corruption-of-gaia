def item_canvas(gid, layer, fig, d, f):
    cv = Canvas()
    dy = HEAD_DY[(d, f)]
    for art, x, y, lay in ITEM_ART.get(gid, {}).get(d, []):
        if lay != layer: continue
        stamp(cv, art, x, y + dy, {k: v for k, v in PAL.items()})
    return cv


def has_layer(gid, layer):
    return any(lay == layer for parts in ITEM_ART.get(gid, {}).values() for (_, _, _, lay) in parts)


def merge(*cvs):
    out = Canvas()
    for cv in cvs:
        for y in range(FH):
            for x in range(FW):
                if cv.px[y][x]: out.px[y][x] = cv.px[y][x]
    return out


