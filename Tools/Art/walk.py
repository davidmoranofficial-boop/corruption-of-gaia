def npc_frame(name, d, f):
    fig, skin, style, hc, beard, looks, items = NPCS[name]
    bm = body_map(fig, d, f)
    layers = [item_canvas(i, 'back', fig, d, f) for i in items]
    layers.append(body_frame(fig, skin, d, f))
    for lk in looks:
        cv = paint_look(lk, bm)
        if lk.details: lk.details(fig, d, f, cv, bm)
        layers.append(outline(cv, keep_out=silhouette(bm)))
    if beard: layers.append(hair_canvas(beard, HAIR3[hc], fig, d, f, beard=True))
    if style != 'bald': layers.append(hair_canvas(style, HAIR3[hc], fig, d, f, capped=any(i in HEAD_ITEMS for i in items)))
    layers += [item_canvas(i, 'front', fig, d, f) for i in items]
    return merge(*layers)


