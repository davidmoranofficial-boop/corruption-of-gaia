def art_rows(text):
    return [r.ljust(FW, '.') for r in text.strip('\n').split('\n')] if text.strip() else []


def hair_canvas(style, ramp, fig, d, f, capped=False, beard=False):
    """Hair (or a beard) for one frame. capped: cut short under a helmet."""
    src = (BEARDS if beard else HAIR)[style]
    rows = art_rows(src.get(d, ''))
    bm = body_map(fig, d, f)
    sil = silhouette(bm)
    cv = Canvas()
    dy = HEAD_DY[(d, f)]
    cols = {'j': ramp[0], 'h': ramp[1], 'H': ramp[2], 'u': ramp[1], 'U': ramp[2], 'r': '#7a3328'}
    for y, r in enumerate(rows):
        Y = y + dy
        if capped and y < 5: continue
        for x, ch in enumerate(r):
            if ch == '.' or not 0 <= Y < FH: continue
            if ch in 'uU' and sil[Y][x]: continue
            if capped and y == 5 and bm[Y][x] == '.': continue
            cv.put(x, Y, cols[ch])
    return outline(cv, keep_out=sil)


