def skirt(ramp, to='shin', flare=True):
    """A skirt or the hem of a robe: fills between the legs down to the knee ('thigh') or the ankle ('shin')."""
    letters = 'rlL' + ('pgG' if to == 'shin' else '')
    def draw(fig, d, f, cv, bm):
        rows = sorted(set(y for x, y in find(bm, letters)))
        for y in rows:
            xs = [x for x in range(FW) if bm[y][x] != '.' and bm[y][x] not in 'jkKcfF']
            if not xs: continue
            x0, x1 = min(xs), max(xs)
            if flare and y == rows[-1]: x0, x1 = x0 - 1, x1 + 1
            for x in range(x0, x1 + 1):
                t = (x - x0) / max(1, x1 - x0)
                cv.put(x, y, ramp[0] if t < 0.2 else ramp[1] if t < 0.7 else ramp[2])
        if rows:
            bottom = rows[-1]
            for x in range(FW):
                if cv.get(x, bottom) and (x + bottom) % 3 == 0: cv.put(x, bottom, ramp[2])   # folds
    return draw


def apron(cloth):
    def draw(fig, d, f, cv, bm):
        chest = find(bm, 'ytT')
        if not chest: return
        top = min(y for _, y in chest) + 1
        if d == 'down':
            xs = sorted(set(x for x, _ in chest)); x0, x1 = xs[1], xs[-2]
            for y in range(top, 21):
                for x in range(x0, x1 + 1):
                    if bm[y][x] != '.' or y >= 16:
                        cv.put(x, y, cloth[0] if x == x0 else cloth[2] if x == x1 else cloth[1])
        elif d == 'up':
            ys = [y for _, y in find(bm, 'bBu')]
            if ys:
                y = ys[0]
                for x in range(6, 10): cv.put(x, y, cloth[1])
        else:
            xs = [x for x, _ in chest]; x0 = min(xs)
            for y in range(top, 21):
                row = [x for x in range(FW) if bm[y][x] != '.']
                if row: cv.put(min(row), y, cloth[1]); cv.put(min(row) - 1 if y >= 16 else min(row), y, cloth[0])
    return draw


def both(*fns):
    def draw(fig, d, f, cv, bm):
        for fn in fns:
            if fn: fn(fig, d, f, cv, bm)
    return draw


