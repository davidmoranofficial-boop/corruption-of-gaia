class Look:
    """What a layer paints: part -> 3-colour ramp (lit, middle, shade). Parts not named stay empty."""
    def __init__(self, parts, details=None):
        self.parts = parts
        self.details = details      # f(fig, d, f, canvas, body) to add stitching, lacing, buckles...


SMALLCLOTHES = ['#b8ad9c', '#958a7a', '#6f665a']


def bare_look(skin):
    sk = SKIN3[skin]
    return Look({'skin': sk, 'eye': ['#1e1a20'] * 3, 'mouth': [sk[2]] * 3, 'chest': SMALLCLOTHES, 'arm': sk, 'fore': sk, 'hand': sk,
                 'belt': SMALLCLOTHES, 'buckle': SMALLCLOTHES, 'thigh': SMALLCLOTHES, 'shin': sk, 'foot': sk, 'line': [OUTLINE] * 3})


# --------------------------------------------------------------------------------------------- drawing

class Canvas:
    def __init__(self):
        self.px = [[None] * FW for _ in range(FH)]

    def put(self, x, y, c):
        if 0 <= x < FW and 0 <= y < FH and c: self.px[y][x] = c

    def get(self, x, y):
        return self.px[y][x] if 0 <= x < FW and 0 <= y < FH else None


def paint_look(look, bmap):
    cv = Canvas()
    for y in range(FH):
        for x in range(FW):
            ch = bmap[y][x]
            if ch == '.' or ch not in PARTS: continue
            part, tone = PARTS[ch]
            r = look.parts.get(part)
            if r: cv.put(x, y, r[tone])
    return cv


def silhouette(bmap):
    return [[bmap[y][x] != '.' for x in range(FW)] for y in range(FH)]


def outline(cv, keep_out=None, colour=OUTLINE):
    """Adds a dark ring round what's drawn. keep_out: a mask (rows of bools) the ring mustn't go on."""
    ring = []
    for y in range(FH):
        for x in range(FW):
            if cv.px[y][x]: continue
            if keep_out and keep_out[y][x]: continue
            if any(cv.get(x + dx, y + dy) and cv.get(x + dx, y + dy) != colour for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                ring.append((x, y))
    for x, y in ring: cv.put(x, y, colour)
    return cv


def stamp(cv, art, ox, oy, colours, under=None, mirror=False):
    """Draws a little text picture at (ox, oy). colours: letter -> colour. under: a mask; pixels there are skipped."""
    rows = art.strip('\n').split('\n')
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch == '.' or ch == ' ': continue
            X = ox + (len(r) - 1 - x if mirror else x)
            Y = oy + y
            if under and 0 <= X < FW and 0 <= Y < FH and under[Y][X]: continue
            cv.put(X, Y, colours[ch])


def find(bmap, letters):
    pts = [(x, y) for y in range(FH) for x in range(FW) if bmap[y][x] in letters]
    return pts


def to_image(cv):
    im = Image.new('RGBA', (FW, FH), (0, 0, 0, 0))
    for y in range(FH):
        for x in range(FW):
            c = cv.px[y][x]
            if c: im.putpixel((x, y), rgb(c) + (255,))
    return im


def make_sheet(frame_fn):
    """frame_fn(d, f) -> Canvas for the down/up/left frames; right is left mirrored."""
    img = Image.new('RGBA', (FW * 3, FH * 4), (0, 0, 0, 0))
    for row, d in enumerate(('down', 'up', 'left', 'right')):
        for f in range(3):
            fr = to_image(frame_fn('left' if d == 'right' else d, f))
            if d == 'right': fr = fr.transpose(Image.FLIP_LEFT_RIGHT)
            img.paste(fr, (f * FW, row * FH), fr)
    return img


# --------------------------------------------------------------------------------------------- the body layer

def body_frame(fig, skin, d, f):
    bm = body_map(fig, d, f)
    cv = paint_look(bare_look(skin), bm)
    # a little life in the face: a cheek of the lit skin, a nose shadow in profile
    return outline(cv)


