# how far the head (and anything worn on it) sits below where it does when standing still
HEAD_DY = {('down', 0): 0, ('down', 1): 0, ('down', 2): 0, ('up', 0): 0, ('up', 1): 0, ('up', 2): 0,
           ('left', 0): 0, ('left', 1): 1, ('left', 2): 1}


def grid(text):
    rows = text.strip('\n').split('\n')
    assert len(rows) == FH, (len(rows), text)
    return [list(r.ljust(FW, '.')[:FW]) for r in rows]


BODY = {k: grid(v) for k, v in BODY.items()}


def female(g, d):
    """The feminine figure: a nipped-in waist and a fuller hip, lashes, a little more chest in profile."""
    g = [list(r) for r in g]
    if d in ('down', 'up'):
        for x in (5, 10):
            if g[13][x] in 'ytT': g[13][x] = 'o'
        if d == 'down':
            for y in range(8):
                for x in range(FW):
                    if g[y][x] == 'e' and g[y - 1][x - 1 if x < 8 else x + 1] in 'sShh': g[y - 1][x - 1 if x < 8 else x + 1] = 'e'
    else:
        for y in range(10, 15):
            if g[y][5] in 'yt' and g[y - 1][5] in 'yt' and y in (12, 13):
                g[y][4] = 'y'
                break
    return g


def body_map(fig, d, f):
    g = BODY[(d, f)]
    return female(g, d) if fig == 'female' else [list(r) for r in g]


def head_top(d, f):
    return 2 + HEAD_DY[(d, f)]


